package core_java_assignment1;

public class Question2 {

	public static void main(String[] args)
	{
		int num =2345;
		num +=8;//num=num+8
		System.out.println("num=num+8 :: "+num);
		num -=8;//num=num-8
		System.out.println("num=num-8 :: "+num);
		num *=5;//num=num*5
		System.out.println("num=num*5 :: "+num);
		
		
		
		

	}

}
